// One-time snapshot of the public DummyJSON product dataset (https://dummyjson.com)
// into typed mock data. Ratings and reviews are intentionally dropped.
// Usage: node scripts/snapshot-products.mjs
import { writeFile } from "node:fs/promises";

const EXCLUDED = new Set(["vehicle", "motorcycle"]);
const res = await fetch("https://dummyjson.com/products?limit=0");
if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
const { products } = await res.json();

const slugify = (s) =>
  s.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const round = (n) => Math.round(n * 100) / 100;

const seen = new Set();
const unique = (slug, id) => {
  const s = seen.has(slug) ? `${slug}-${id}` : slug;
  seen.add(s);
  return s;
};

const out = products
  .filter((p) => !EXCLUDED.has(p.category))
  .map((p) => ({
    id: String(p.id),
    slug: unique(slugify(p.title), p.id),
    title: p.title,
    description: p.description,
    brand: p.brand ?? null,
    category: p.category,
    tags: p.tags,
    price: p.price,
    // DummyJSON lists the sale price with a discount %; derive the original list price.
    listPrice: p.discountPercentage >= 5 ? round(p.price / (1 - p.discountPercentage / 100)) : null,
    stock: p.stock,
    sku: p.sku,
    weight: p.weight,
    dimensions: p.dimensions,
    warranty: p.warrantyInformation,
    shipping: p.shippingInformation,
    returnPolicy: p.returnPolicy,
    images: p.images,
    thumbnail: p.thumbnail,
  }));

const header = `// AUTO-GENERATED by scripts/snapshot-products.mjs — do not edit by hand.
// Source: https://dummyjson.com/products (public demo dataset). Ratings/reviews omitted.
import type { RawProduct } from "@/lib/types";

export const rawProducts: RawProduct[] = `;
await writeFile("src/data/products.generated.ts", header + JSON.stringify(out, null, 2) + ";\n");
console.log(`Wrote ${out.length} products`);
